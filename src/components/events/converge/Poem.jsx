export default function PoemDisplay() {
  const [showFullPoem, setShowFullPoem] = useState(false);

  // Split the poem into lines and get the first 4 lines for preview
  const lines = poem.trim().split("\n");
  const previewLines = lines.slice(0, 4).join("\n");

  return (
    <div className="w-full mx-auto p-6 bg-white shadow-lg rounded-lg">
      {showFullPoem ? (
        // Full poem inside a scrollable container with Read More button at the bottom
        <div className="max-h-96 overflow-y-auto scrollbar-thin scrollbar-thumb-teal-500 scrollbar-track-gray-100 flex flex-col">
          <div className="text-lg text-gray-800 font-tamil whitespace-pre-line p-2 flex-1">
            {poem}
          </div>
          <button
            onClick={() => setShowFullPoem(false)} // Already expanded, so no action needed
            className="mt-4 px-4 py-2 bg-teal-500 text-white rounded-md hover:bg-teal-600 transition self-center mb-4"
          >
            Read less
          </button>
        </div>
      ) : (
        // Preview (first 4 lines) with Read More button
        <div>
          <div className="text-lg text-gray-800 font-tamil whitespace-pre-line">
            {previewLines}
          </div>
          <button
            onClick={() => setShowFullPoem(true)}
            className="mt-4 px-4 py-2 bg-teal-500 text-white rounded-md hover:bg-teal-600 transition"
          >
            Read More
          </button>
        </div>
      )}
    </div>
  );
}
